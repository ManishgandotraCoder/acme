import { Alert, Badge, Button, Group, Paper, Stack, Text, Textarea, Title } from '@mantine/core'
import { IconSparkles } from '@tabler/icons-react'
import { useMutation } from '@tanstack/react-query'
import { useState } from 'react'
import { assistantApi } from '@/features/assistant/api'
import type { AskResult } from '@/features/assistant/types'

const EXAMPLES = [
  'What is the average salary of data analysts in Germany?',
  'How much do we pay software engineers in India?',
  'Which department has the highest average pay?',
  'Compare product manager salaries across countries',
  'Give me pay statistics for Japan',
]

const METRIC_LABELS: Record<string, string> = {
  org_summary: 'Org summary',
  country_stats: 'Country stats',
  job_title_stats: 'Job title stats',
  department_stats: 'Department stats',
  unsupported: 'Not understood',
}

export function AskPage() {
  const [question, setQuestion] = useState('')
  const [answers, setAnswers] = useState<AskResult[]>([])
  const ask = useMutation({
    mutationFn: (q: string) => assistantApi.ask(q),
    onSuccess: (result) => setAnswers((previous) => [result, ...previous]),
  })

  const submit = (q: string) => {
    const trimmed = q.trim()
    if (!trimmed) return
    setQuestion(trimmed)
    ask.mutate(trimmed)
  }

  return (
    <Stack maw={860}>
      <div>
        <Title order={2}>Ask about pay</Title>
        <Text c="dimmed" size="sm">
          Ask in plain English. A local AI model (Ollama) interprets the question; every number is
          calculated from the salary database, never generated by the model.
        </Text>
      </div>

      <form
        onSubmit={(e) => {
          e.preventDefault()
          submit(question)
        }}
      >
        <Stack gap="xs">
          <Textarea
            label="Your question"
            placeholder="e.g. What do software engineers earn in India?"
            autosize
            minRows={2}
            maxLength={500}
            value={question}
            onChange={(e) => setQuestion(e.currentTarget.value)}
            onKeyDown={(e) => {
              if (e.key === 'Enter' && !e.shiftKey) {
                e.preventDefault()
                submit(question)
              }
            }}
          />
          <Group justify="space-between">
            <Group gap={6}>
              {EXAMPLES.map((example) => (
                <Button key={example} size="compact-xs" variant="light" color="gray" onClick={() => submit(example)}>
                  {example}
                </Button>
              ))}
            </Group>
            <Button type="submit" leftSection={<IconSparkles size={16} />} loading={ask.isPending} disabled={!question.trim()}>
              Ask
            </Button>
          </Group>
        </Stack>
      </form>

      {ask.error && (
        <Alert color="orange" title="Couldn't get an answer">
          {ask.error.message} The Pay insights page still works without the AI assistant.
        </Alert>
      )}

      {answers.map((a, i) => (
        <Paper key={answers.length - i} withBorder p="md">
          <Text size="sm" c="dimmed" mb={4}>
            {a.question}
          </Text>
          <Text fw={500}>{a.answer}</Text>
          <Group gap={6} mt="sm">
            <Badge variant="light">{METRIC_LABELS[a.intent.metric] ?? a.intent.metric}</Badge>
            {a.intent.country && <Badge variant="outline">Country: {a.intent.country}</Badge>}
            {a.intent.job_title && <Badge variant="outline">Job title: {a.intent.job_title}</Badge>}
            {a.intent.department && <Badge variant="outline">Department: {a.intent.department}</Badge>}
          </Group>
        </Paper>
      ))}
    </Stack>
  )
}
